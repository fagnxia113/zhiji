  await page.getByRole("navigation", { name: "项目列表", exact: true }).getByRole("button", { name: /专题调研/ }).click();
  await switchProject.click();
  const recent = page.getByRole("navigation", { name: "最近项目", exact: true });
  assert.deepEqual(await recent.getByRole("button").allTextContents(), ["专题调研", "季度汇报"]);
