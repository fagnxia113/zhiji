import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { installFixture } from "./workbench-fixture.mjs";

function seed() {
  const f = window.__fixture;
  f.work.projects.push({ id: "p1", name: "季度汇报", archived: false }, { id: "p2", name: "专题调研", archived: false }, { id: "p3", name: "历史项目", archived: true });
  f.hub.resources.push({ id: "r1", title: "调研报告.docx", path: "D:\\work\\调研报告.docx", contentStatus: "metadata_only" }, { id: "r2", title: "评审意见.pdf", path: "D:\\work\\评审意见.pdf", contentStatus: "metadata_only" });
  f.hub.resourceLinks.push({ resourceId: "r1", projectId: "p1", role: "output" }, { resourceId: "r2", projectId: "p1", role: "reference" });
  localStorage.setItem("zhiji:last-project", "p1");
  if (!localStorage.getItem("zhiji:project-shortcuts")) localStorage.setItem("zhiji:project-shortcuts", "invalid old cache");
}

