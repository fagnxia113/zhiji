const errors = [];
page.on("pageerror", e => errors.push(e.message));
await page.clock.install({ time: new Date("2026-10-02T10:00:00+08:00") });
await page.addInitScript({ content: `(${installFixture.toString()})(); (${seed.toString()})();` });
