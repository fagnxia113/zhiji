  await hub.getByRole("tab", { name: "资料", exact: true }).click();
  await hub.getByRole("button", { name: /^调研报告.docx/ }).click();
  const detail = hub.getByRole("region", { name: "资料详情" });
  await detail.getByRole("button", { name: "记录相关进展" }).click();
  const input = () => page.getByRole("textbox", { name: "项目进展内容", exact: true });
  await input().fill("已提交报告初稿，等待评审");
