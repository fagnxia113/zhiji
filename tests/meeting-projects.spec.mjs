import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { installFixture } from "./workbench-fixture.mjs";

function seed() {
  window.__fixture.work.projects.push({id:"p",name:"海外数据中心",archived:false,themeIds:[]},{id:"q",name:"联合研究",archived:false,themeIds:[]});
}
const browser=await chromium.launch({channel:process.env.BROWSER_CHANNEL || "chrome",headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},locale:"zh-CN",timezoneId:"Asia/Shanghai"});
const errors=[]; page.on("pageerror",e=>errors.push(e.message));
await page.addInitScript({content:`(${installFixture.toString()})(); (${seed.toString()})();`});
try {
  await page.goto(process.env.TEST_URL || "http://127.0.0.1:1422");
  await page.getByRole("button",{name:"会议资料",exact:true}).click();
  await page.locator(".meeting-item").first().click();
  const association=page.getByRole("combobox",{name:"会议所属项目",exact:true});
  assert.equal(await association.inputValue(),"");
  await page.evaluate(()=>{window.__fixture.failMeetingProject=true;});
  await association.selectOption("p");
  await page.locator(".meeting-project").getByRole("alert").getByText(/项目关联失败/).waitFor();
  assert.equal(await page.evaluate(()=>window.__fixture.work.links["meeting:m1"]),undefined);
  await page.evaluate(()=>{window.__fixture.failMeetingProject=false;});
  await association.selectOption("p");
  await page.getByRole("button",{name:"进入项目",exact:true}).waitFor();
  await page.getByRole("button",{name:"进入项目",exact:true}).click();
  const hub=page.getByRole("region",{name:"项目详情"});
  await hub.getByRole("tab",{name:"活动",exact:true}).click();
  assert.equal(await hub.locator(".hub-activity-list article").count(),1);
  await hub.locator(".hub-activity-list").getByText("产品体验优化 · 周例会",{exact:true}).waitFor();
  await hub.getByRole("button",{name:"打开会议记录",exact:true}).click();
  assert.equal(await association.inputValue(),"p");
  await mkdir(".tmp/ui-verification",{recursive:true});
  await page.screenshot({path:".tmp/ui-verification/meeting-project.png"});
  await page.getByRole("button",{name:"进入项目",exact:true}).click();
  await hub.getByRole("tab",{name:"资料",exact:true}).click();
  const folder=page.locator(".hub-project-folder");
  await page.evaluate(()=>{window.__fixture.pickedFiles=null;});
  await folder.getByRole("button",{name:"关联项目文件夹",exact:true}).click();
  assert.equal(await page.evaluate(()=>window.__fixture.work.projects[0].folderPath),undefined,"cancel does not save a folder");
  await page.evaluate(()=>{window.__fixture.pickedFiles="D:\\资料\\海外数据中心";window.__fixture.failFolder=true;});
  await folder.getByRole("button",{name:"关联项目文件夹",exact:true}).click();
  await hub.getByRole("alert").getByText(/文件夹关联失败/).waitFor();
  await page.evaluate(()=>{window.__fixture.failFolder=false;});
  await folder.getByRole("button",{name:"关联项目文件夹",exact:true}).click();
  await folder.getByRole("button",{name:"打开项目文件夹",exact:true}).waitFor();
  await folder.getByRole("button",{name:"打开项目文件夹",exact:true}).click();
  await page.waitForFunction(()=>window.__fixture.workCalls.some(c=>c.action==="open_project_folder"&&c.args.projectId==="p"));
  await folder.getByText("文件夹设置",{exact:true}).click();
  await folder.getByText("D:\\资料\\海外数据中心",{exact:true}).waitFor();
  await page.screenshot({path:".tmp/ui-verification/project-folder.png"});
  await folder.getByRole("button",{name:"解除文件夹关联",exact:true}).click();
  await folder.getByRole("button",{name:"关联项目文件夹",exact:true}).waitFor();
  await hub.getByRole("tab",{name:"活动",exact:true}).click();
  await hub.getByRole("button",{name:"打开会议记录",exact:true}).click();
  await association.selectOption("");
  await page.waitForFunction(()=>!window.__fixture.work.links["meeting:m1"]);
  assert.equal(await page.getByRole("button",{name:"进入项目",exact:true}).count(),0);
  await association.selectOption("q");
  await page.getByRole("button",{name:"进入项目",exact:true}).click();
  await hub.getByRole("heading",{name:"联合研究",exact:true}).waitFor();
  await hub.getByRole("tab",{name:"活动",exact:true}).click();
  assert.equal(await hub.locator(".hub-activity-list article").count(),1);
  await hub.getByRole("button",{name:"打开会议记录",exact:true}).click();
  await page.setViewportSize({width:400,height:850});
  await page.screenshot({path:".tmp/ui-verification/meeting-project-narrow.png"});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  console.log("PASS: optional meeting project, bidirectional navigation, failed assignment, reassignment, project folder cancel/save/open/unlink and narrow layout.");
} finally { await browser.close(); }
